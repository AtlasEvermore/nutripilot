// Splits the master dictionary (i18n.js, keyed by French text) into one file per language,
// so each phone only downloads the language it uses. Run: npm run i18n
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { DICT } = await import(path.join(root, 'i18n.js'));
const codes = new Set();
Object.values(DICT).forEach((entry) => Object.keys(entry).forEach((code) => codes.add(code)));
fs.mkdirSync(path.join(root, 'i18n'), { recursive: true });
for (const code of codes) {
  const out = {};
  for (const [fr, entry] of Object.entries(DICT)) if (entry[code]) out[fr] = entry[code];
  const file = path.join(root, 'i18n', `${code}.js`);
  fs.writeFileSync(file, `// Generated by scripts/build-i18n.mjs from i18n.js. Do not edit by hand.\nexport default ${JSON.stringify(out)};\n`);
  console.log(code, Object.keys(out).length, 'lines', fs.statSync(file).size, 'bytes');
}
